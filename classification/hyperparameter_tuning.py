"""
hyperparameter_tuning.py

TRAINING CLASSIFIER PIPELINE (1/?)
----------------------------------
Performs the hyperparameter tuning of the classification model (2D-CNN) with Optuna (TPE sampler +
Hyperband pruner), taking as input the desired Time-Frequency Representation (RTF) of each
fragment. Each trial is trained on the training folds and evaluated on one validation fold
(fold 1). The objective variable is the best EMA of the validation macro PR-AUC (see
src/tuning/tune.py).

Requires:
    classification/splits/splits.csv
    dataset/dataset/{RTF}/{x}.tiff

Generates:
    classification/results/tensorboard/optuna/{type}/trial_{n}
        TensorBoard logs of each trial (training curves and hyperparameters)
    If --save:
        classification/results/optuna/{type}/{type}.db
            Optuna study (if it already exists, the study is resumed)
        classification/results/optuna/{type}/figures/{figure}.{png, svg, html}
            Optuna figures: optimization_history, param_importances, intermediate_values,
            parallel_coordinate and slice

Execution:
    python classification/hyperparameter_tuning.py -t <type> [-s]
        - type: RTF used as input of the model:
            - STFT
        --s, --save: Save the Optuna study and its figures
"""


import argparse
from pathlib import Path

import pandas as pd
import optuna
import optuna.visualization as vis
import plotly.graph_objects as go

from src.data.class_to_idx import FILTERED_IDX
from src.tuning.tune import tune


# Config
DF_CONFIG = {
    "image_col": "id",
    "label_col": "label",
    "fold_col": "fold",
}
N_TRIALS = 5  # Number of trials for hyperparameter tuning

# Representaciones Tiempo-Frecuencia disponibles
RTFS = ["STFT"]

# Paths
CLASSIFICATION_PATH = Path("classification")
SPLITS_PATH = CLASSIFICATION_PATH / "splits" / "splits.csv"

DATASET_PATH = Path("dataset")
DATASET_DATASET_PATH = DATASET_PATH / "dataset"
SPECTROGRAMS_PATH = DATASET_DATASET_PATH / "spectrogram"

PATHS = {
    "STFT": SPECTROGRAMS_PATH
}


RESULTS_PATH = CLASSIFICATION_PATH / "results"
RESULTS_OPTUNA_PATH = RESULTS_PATH / "optuna"


def save_figure(
        fig: go.Figure,
        output_dir: Path,
        filename: str,
        formats: tuple[str]=("png", "svg", "html"),
        scale=5
    ) -> None:
    """
    Saves a Plotly figure (the kind returned by optuna.visualization functions) in various formats. 

    Parameters
    ----------
    fig: go.Figure
        Plotly figure (go.Figure) returned by optuna.visualization.plot_*

    output_dir: Path
        Directory where the files will be saved
    filename: str
        Base filename, without extension
    formats: tuple[str], optional
        Any combination of "png", "svg", "html" (default = ("png", "svg", "html")).
    scale: int, optional
        Resolution factor for PNG (default = 5).
    """
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    if "png" in formats:
        fig.write_image(output_dir / f"{filename}.png", scale=scale)

    if "svg" in formats:
        fig.write_image(output_dir / f"{filename}.svg")

    if "html" in formats:
        # Versión interactiva: zoom, hover con valores exactos, pan, etc.
        fig.write_html(output_dir / f"{filename}.html", include_plotlyjs="cdn")


def save_figures(study: optuna.study.Study, rtf_type: str) -> None:
    """
    Saves the figures generated by Optuna for hyperparameter tuning.

    Parameters
    ----------
    study: optuna.study.Study
        The Optuna study object containing the results of the hyperparameter tuning.
    rtf_type: str
        The type of RTF (e.g., "STFT") for which the hyperparameter tuning was performed.
    """

    FIGURES_PATH = RESULTS_OPTUNA_PATH / rtf_type / "figures"

    # Generate Figures
    fig1 = vis.plot_optimization_history(study)
    fig2 = vis.plot_param_importances(study)
    fig3 = vis.plot_intermediate_values(study)
    top_params = list(optuna.importance.get_param_importances(study).keys())[:5]
    fig4 = vis.plot_parallel_coordinate(study, params=top_params)
    fig5 = vis.plot_slice(study, params=top_params)

    # Save Figures
    save_figure(fig1, FIGURES_PATH, "optimization_history")
    save_figure(fig2, FIGURES_PATH, "param_importances")
    save_figure(fig3, FIGURES_PATH, "intermediate_values")
    save_figure(fig4, FIGURES_PATH, "parallel_coordinate")
    save_figure(fig5, FIGURES_PATH, "slice")


def hyperparameter_tuning(rtf_type: str, save: bool) -> None:
    """
    Performs the hyperparameter tuning of the classification model for the given RTF:
        1. Load the data splits
        2. Create and optimize the Optuna study (N_TRIALS trials, validation on fold 1), named as
           the RTF type
        3. If `save`, save the figures of the study

    Parameters
    ----------
    rtf_type: str
        The type of RTF (e.g., "STFT") used as input of the model
    save: bool
        Whether to save the Optuna study and its figures or not
    """

    # Load data
    print("Loading data...")
    df = pd.read_csv(SPLITS_PATH)

    origin = PATHS[rtf_type]  # Origin folder for the input model

    study = tune(
        df=df,
        df_config=DF_CONFIG,
        origin=origin,
        class_to_idx=FILTERED_IDX,
        study_name=rtf_type,
        fold=1,
        n_trials=N_TRIALS,
        in_channels=1,
        num_classes=4,
        save=save,
    )

    if save:
        save_figures(study, rtf_type)


def main():
    print()
    parser = argparse.ArgumentParser(description="Perform hyperparameter tuning for classification model, given the input")
    parser.add_argument("-t", "--type", required=True, choices=RTFS, help="Type of RTF used as input of the model")
    parser.add_argument("-s", "--save", required=False, action="store_true", help="Whether to save the results or not")
    args = parser.parse_args()
    rtf = args.type
    save = args.save

    hyperparameter_tuning(rtf, save)

    
if __name__ == "__main__":
    main()
